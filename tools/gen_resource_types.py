#!/usr/bin/env python3
"""Generate the C# and C++ resource type tables from data/resource-types.tsv.

usage: python tools/gen_resource_types.py      (run from the repository root)

Columns: id (hex), games (3M = The Sims 3 + Medieval, 4 = The Sims 4), tag, name, category.
The same ID can have a different meaning in each game, so rows are per game.
"""
import sys

if sys.version_info < (3, 12):
    sys.exit("DBPFX tools require Python 3.12 or newer (this is %d.%d)" % sys.version_info[:2])

import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "data", "resource-types.tsv")
CS = os.path.join(ROOT, "managed", "src", "DBPFX", "KnownTypes.g.cs")
CPP = os.path.join(ROOT, "native", "include", "dbpfx", "known_types.inc")

GAMES_CS = {"3M": "Games.Sims3AndMedieval", "4": "Games.Sims4"}
GAMES_CPP = {"3M": "0x3", "4": "0x4"}  # bit 0 sims3, bit 1 medieval, bit 2 sims4


def rows():
    for line in open(SRC, encoding="utf-8"):
        if not line.strip() or line.startswith("#"):
            continue
        ident, games, tag, name, category = (line.rstrip("\n").split("\t") + [""] * 5)[:5]
        yield int(ident, 16), games, tag, name, category


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main():
    data = sorted(rows(), key=lambda r: (r[0], r[1]))
    with open(CS, "w", encoding="utf-8", newline="\n") as f:
        f.write("// <auto-generated> from data/resource-types.tsv by tools/gen_resource_types.py - do not edit </auto-generated>\n")
        f.write("using System.Collections.Generic;\n\nnamespace DBPFX\n{\n    public static partial class KnownTypes\n    {\n")
        f.write("        static partial void Fill(List<ResourceTypeInfo> table)\n        {\n")
        for ident, games, tag, name, category in data:
            f.write(f'            table.Add(new ResourceTypeInfo(0x{ident:08X}, "{esc(tag)}", "{esc(name)}", "{esc(category)}", {GAMES_CS[games]}));\n')
        f.write("        }\n    }\n}\n")
    with open(CPP, "w", encoding="utf-8", newline="\n") as f:
        f.write("// <auto-generated> from data/resource-types.tsv by tools/gen_resource_types.py - do not edit </auto-generated>\n")
        f.write("// { id, games mask (1 = sims3, 2 = medieval, 4 = sims4), tag, name, category }\n")
        for ident, games, tag, name, category in data:
            f.write(f'{{0x{ident:08X}u, {GAMES_CPP[games]}, "{esc(tag)}", "{esc(name)}", "{esc(category)}"}},\n')
    print(f"{len(data)} rows -> {os.path.relpath(CS, ROOT)}, {os.path.relpath(CPP, ROOT)}")


if __name__ == "__main__":
    main()
